export function getStoryOfTheDay(date = new Date()) {
  const dayIndex = Math.floor(date.getTime() / 86400000) % STORIES.length;
  return STORIES[dayIndex];
}
export function getStoryById(id) {
  return STORIES.find((s) => s.id === id) || null;
}
